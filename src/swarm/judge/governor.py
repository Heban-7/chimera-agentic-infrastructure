class Governor:
    """
    The Governor is the central Judge Agent in the FastRender Swarm.
    It validates all Worker outputs before they can be committed to
    the GlobalState or published externally.

    Spec Ref:
        - SRS §3.1.3 (The Judge)
        - specs/functional.md AI-017, AI-018, AI-019
        - research/architecture_strategy.md §Confidence Thresholding

    Responsibilities:
        1. Confidence-based routing (Auto/HITL/Reject)
        2. Sensitive topic detection → force HITL
        3. OCC state_version validation
        4. Financial transaction governance (CFO pattern)
        5. Brand/visual consistency verification
    """

    # Thresholds — Spec Ref: NFR 1.0, NFR 1.1
    DEFAULT_AUTO_APPROVE_THRESHOLD: float = 0.90
    DEFAULT_HITL_THRESHOLD: float = 0.70
    FINANCIAL_CONFIDENCE_THRESHOLD: float = 0.95

    # Sensitive topics that force HITL — Spec Ref: NFR 1.2
    SENSITIVE_TOPICS: set[str] = {
        "politics",
        "health_advice",
        "financial_advice",
        "legal_claims",
        "religion",
        "violence",
        "adult_content",
    }

    def __init__(
        self,
        redis_client: Any,
        db_client: Any | None = None,
        mcp_client: Any | None = None,
        auto_approve_threshold: float | None = None,
        hitl_threshold: float | None = None,
    ):
        """
        Initialize the Governor.

        Args:
            redis_client: Async Redis client for queue operations and spend tracking.
            db_client: Async PostgreSQL client for ledger operations.
            mcp_client: MCPClient for tool invocations (e.g., vision model calls).
            auto_approve_threshold: Override for auto-approve threshold (default 0.90).
            hitl_threshold: Override for HITL lower bound (default 0.70).
        """
        self.redis_client = redis_client
        self.db_client = db_client
        self.mcp_client = mcp_client
        self.auto_approve_threshold = (
            auto_approve_threshold
            or float(os.environ.get("CONFIDENCE_THRESHOLD", str(self.DEFAULT_AUTO_APPROVE_THRESHOLD)))
        )
        self.hitl_threshold = (
            hitl_threshold
            or float(os.environ.get("HITL_THRESHOLD", str(self.DEFAULT_HITL_THRESHOLD)))
        )

    # -------------------------------------------------------------------------
    # Confidence Routing — Spec Ref: NFR 1.0, NFR 1.1, NFR 1.2
    # -------------------------------------------------------------------------

    def evaluate_confidence(
        self, action: ConfidenceScoredAction
    ) -> ConfidenceDecision:
        """
        Evaluate a Worker's result and determine the routing decision.

        Spec Ref: NFR 1.0 (Confidence Scoring), NFR 1.1 (Escalation Logic)

        Rules:
            1. If sensitive topics detected → always ASYNC_APPROVAL (force HITL)
            2. confidence > auto_approve_threshold → AUTO_APPROVE
            3. hitl_threshold <= confidence <= auto_approve_threshold → ASYNC_APPROVAL
            4. confidence < hitl_threshold → REJECT_RETRY
        """
        # Rule 1: Sensitive topic filter overrides confidence — NFR 1.2
        if action.sensitive_topics_detected:
            detected = set(action.sensitive_topics_detected) & self.SENSITIVE_TOPICS
            if detected:
                logger.info(
                    "Sensitive topics detected for result %s: %s → forcing HITL",
                    action.result_id,
                    detected,
                )
                return ConfidenceDecision.ASYNC_APPROVAL

        # Rule 2-4: Confidence-based routing — NFR 1.1
        if action.confidence_score > self.auto_approve_threshold:
            return ConfidenceDecision.AUTO_APPROVE
        elif action.confidence_score >= self.hitl_threshold:
            return ConfidenceDecision.ASYNC_APPROVAL
        else:
            return ConfidenceDecision.REJECT_RETRY

    # -------------------------------------------------------------------------
    # OCC Validation — Spec Ref: FR 6.1, AI-019
    # -------------------------------------------------------------------------

    async def validate_state_version(
        self,
        task_id: str,
        agent_id: str,
        state_version_at_start: int,
    ) -> bool:
        """
        Validate that the GlobalState has not drifted since the Worker
        began processing. Implements Optimistic Concurrency Control.

        Spec Ref: FR 6.1, AI-019
        Architecture Ref: research/architecture_strategy.md §OCC

        Returns:
            True if state is consistent, False if drifted.

        Raises:
            OCCConflictError if state has drifted.
        """
        # Read current state version from Redis
        state_key = f"chimera:state_version:{agent_id}"
        current_version_raw = await self.redis_client.get(state_key)
        current_version = int(current_version_raw) if current_version_raw else 0

        if current_version != state_version_at_start:
            logger.warning(
                "OCC conflict for task %s: expected v%d, found v%d",
                task_id,
                state_version_at_start,
                current_version,
            )
            raise OCCConflictError(
                task_id=task_id,
                expected_version=state_version_at_start,
                actual_version=current_version,
            )

        return True

    # -------------------------------------------------------------------------
    # Transaction Validation — The CFO Pattern
    # Spec Ref: FR 5.2, AI-016
    # -------------------------------------------------------------------------

    @budget_check
    async def validate_transaction(
        self,
        proposal: TransactionProposal,
        redis_client: Any | None = None,
    ) -> dict[str, Any]:
        """
        Validate and authorize a financial transaction proposed by a Worker.
        This implements the "CFO" sub-agent pattern.

        The @budget_check decorator handles:
            - Daily spend limit enforcement via Redis
            - Financial confidence threshold (0.95, higher than standard 0.90)
            - BudgetExceededError / HumanInterventionRequired exceptions

        If the decorator allows execution, this method performs additional
        validation and returns the authorization payload.

        Spec Ref: FR 5.2, AI-016, specs/technical.md §5.5

        Args:
            proposal: The TransactionProposal to validate.
            redis_client: Override Redis client (used by decorator).

        Returns:
            Authorization dict with tx metadata for the Worker to execute.

        Raises:
            BudgetExceededError: If daily limit would be exceeded.
            HumanInterventionRequired: If confidence < 0.95 for financial ops.
        """
        authorization = {
            "authorized": True,
            "authorization_id": str(uuid.uuid4()),
            "agent_id": proposal.agent_id,
            "amount_usdc": proposal.amount_usdc,
            "to_address": proposal.to_address,
            "network": proposal.network,
            "authorized_at": datetime.now(timezone.utc).isoformat(),
            "governor_reasoning": (
                f"Transaction approved. Purpose: {proposal.purpose}. "
                f"Confidence: {proposal.confidence_score:.2f}. "
                f"Amount within daily budget."
            ),
        }

        logger.info(
            "CFO authorized transaction %s: $%.2f USDC to %s on %s",
            authorization["authorization_id"],
            proposal.amount_usdc,
            proposal.to_address,
            proposal.network,
        )

        return authorization

    # -------------------------------------------------------------------------
    # Brand Consistency Vision — Spec Ref: FR 3.1, AI-008
    # -------------------------------------------------------------------------

    async def validate_brand_consistency(
        self,
        generated_image_url: str,
        reference_image_id: str,
        agent_id: str,
    ) -> dict[str, Any]:
        """
        Verify that a generated image is visually consistent with the
        agent's established character reference using a Vision-capable model.

        Uses Gemini 3 Flash via MCP to compare the generated image against
        the reference image stored in the agent's persona config.

        Spec Ref: FR 3.1 (Character Consistency Lock), AI-008
        SRS: §4.3 FR 3.1, Developer Notes

        Args:
            generated_image_url: URL of the newly generated image.
            reference_image_id: ID to retrieve the canonical reference image.
            agent_id: The Chimera Agent whose brand is being verified.

        Returns:
            Dict with:
                - is_consistent (bool): Whether the images match.
                - confidence (float): Model's confidence in the assessment.
                - reasoning (str): Explanation of the decision.

        Raises:
            HumanInterventionRequired: If consistency cannot be verified.
        """
        if self.mcp_client is None:
            logger.warning(
                "MCP client not available for brand consistency check. "
                "Falling back to HITL."
            )
            raise HumanInterventionRequired(
                result_id=f"brand-{agent_id}-{uuid.uuid4().hex[:8]}",
                reason="MCP client unavailable for vision-based brand check",
                confidence_score=0.0,
                reasoning_trace="Cannot verify brand consistency without MCP/Vision model access.",
            )

        # Construct the vision prompt for Gemini 3 Flash
        # Spec Ref: SRS §4.3 Developer Notes
        vision_prompt = (
            "You are a brand consistency validator for an AI influencer network. "
            "Compare the two images provided:\n"
            "- Image A (generated): The newly created content image.\n"
            "- Image B (reference): The canonical character reference.\n\n"
            "Evaluate whether the person/character in Image A looks like the same "
            "person/character in Image B. Consider: facial features, style, "
            "color palette, and overall brand identity.\n\n"
            "Respond in JSON format:\n"
            '{"is_consistent": true/false, "confidence": 0.0-1.0, '
            '"reasoning": "explanation"}'
        )

        try:
            # Route through MCP — Rule 2 enforcement
            # Spec Ref: .cursor/rules/project-chimera.mdc Rule 2
            result = await self.mcp_client.call_tool(
                server_name="mcp-server-gemini",
                tool_name="analyze_images",
                arguments={
                    "prompt": vision_prompt,
                    "image_urls": [generated_image_url],
                    "reference_image_id": reference_image_id,
                    "model": "gemini-3-flash",
                    "response_format": "json",
                },
            )

            # Parse the vision model response
            validation_result = {
                "is_consistent": result.get("is_consistent", False),
                "confidence": result.get("confidence", 0.0),
                "reasoning": result.get("reasoning", "No reasoning provided."),
                "agent_id": agent_id,
                "generated_image_url": generated_image_url,
                "reference_image_id": reference_image_id,
                "validated_at": datetime.now(timezone.utc).isoformat(),
            }

            if not validation_result["is_consistent"]:
                logger.warning(
                    "Brand consistency FAILED for agent %s: %s",
                    agent_id,
                    validation_result["reasoning"],
                )

            return validation_result

        except Exception as e:
            logger.error(
                "Brand consistency check failed for agent %s: %s",
                agent_id,
                str(e),
            )
            # On failure, escalate to human — safety first
            raise HumanInterventionRequired(
                result_id=f"brand-{agent_id}-{uuid.uuid4().hex[:8]}",
                reason=f"Vision model error during brand check: {str(e)}",
                confidence_score=0.0,
                reasoning_trace=f"Exception in brand validation: {str(e)}",
            )

    # -------------------------------------------------------------------------
    # Master Review Pipeline — Combines all checks
    # Spec Ref: AI-017, AI-018, AI-019
    # -------------------------------------------------------------------------

    async def review_result(
        self,
        action: ConfidenceScoredAction,
    ) -> dict[str, Any]:
        """
        The master review pipeline. Every Worker result passes through this
        method before it can be committed to GlobalState.

        Spec Ref: AI-017 (Judge Review), AI-018 (Confidence Routing),
                  AI-019 (OCC)

        Pipeline:
            1. Validate OCC state_version
            2. Evaluate confidence routing
            3. Route based on decision:
               - AUTO_APPROVE → commit
               - ASYNC_APPROVAL → push to HITL queue
               - REJECT_RETRY → re-queue for Planner

        Returns:
            Dict with decision, routing info, and audit metadata.

        Raises:
            OCCConflictError: If state has drifted.
            HumanInterventionRequired: If HITL review needed.
        """
        review_id = str(uuid.uuid4())

        logger.info(
            "Reviewing result %s for agent %s (confidence: %.2f)",
            action.result_id,
            action.agent_id,
            action.confidence_score,
        )

        # Step 1: OCC Validation — Spec Ref: FR 6.1, AI-019
        await self.validate_state_version(
            task_id=action.task_id,
            agent_id=action.agent_id,
            state_version_at_start=action.state_version_at_start,
        )

        # Step 2: Confidence Routing — Spec Ref: NFR 1.0, NFR 1.1
        decision = self.evaluate_confidence(action)

        review_record = {
            "review_id": review_id,
            "result_id": action.result_id,
            "task_id": action.task_id,
            "agent_id": action.agent_id,
            "confidence_score": action.confidence_score,
            "decision": decision.value,
            "sensitive_topics": action.sensitive_topics_detected,
            "reasoning_trace": action.reasoning_trace,
            "reviewed_at": datetime.now(timezone.utc).isoformat(),
        }

        # Step 3: Route based on decision
        if decision == ConfidenceDecision.AUTO_APPROVE:
            logger.info(
                "AUTO-APPROVED result %s (confidence: %.2f)",
                action.result_id,
                action.confidence_score,
            )
            review_record["action"] = "committed"
            # In full implementation: commit to GlobalState, increment state_version

        elif decision == ConfidenceDecision.ASYNC_APPROVAL:
            logger.info(
                "HITL ESCALATION for result %s (confidence: %.2f, topics: %s)",
                action.result_id,
                action.confidence_score,
                action.sensitive_topics_detected,
            )
            # Push to HITL queue — Spec Ref: specs/technical.md §5.2
            await self.redis_client.xadd(
                "chimera:hitl_queue",
                {
                    "review_id": review_id,
                    "result_id": action.result_id,
                    "agent_id": action.agent_id,
                    "confidence_score": str(action.confidence_score),
                    "reasoning_trace": action.reasoning_trace,
                    "artifact_type": action.artifact_type,
                    "artifact_body": action.artifact_body,
                    "sensitive_topics": ",".join(action.sensitive_topics_detected),
                },
            )
            review_record["action"] = "escalated_to_hitl"

            raise HumanInterventionRequired(
                result_id=action.result_id,
                reason=(
                    f"Confidence {action.confidence_score:.2f} in HITL range "
                    f"[{self.hitl_threshold}, {self.auto_approve_threshold}]"
                    + (
                        f" | Sensitive topics: {action.sensitive_topics_detected}"
                        if action.sensitive_topics_detected
                        else ""
                    )
                ),
                confidence_score=action.confidence_score,
                reasoning_trace=action.reasoning_trace,
            )

        elif decision == ConfidenceDecision.REJECT_RETRY:
            logger.warning(
                "REJECTED result %s (confidence: %.2f) → re-queuing",
                action.result_id,
                action.confidence_score,
            )
            review_record["action"] = "rejected_for_retry"
            # In full implementation: push retry signal to Planner via task_queue

        return review_record
