# The Budget Check Decorator — Spec Ref: FR 5.2, AI-016
# =============================================================================


def budget_check(func: Callable) -> Callable:
    """
    Decorator that enforces daily spend limits before executing any
    financial transaction. Uses Redis-backed daily spend tracking.

    MUST be applied to any function that calls coinbase-agentkit
    send_payment, native_transfer, or deploy_token.

    Spec Ref: FR 5.2 (CFO Sub-Agent), AI-016
    Architecture Ref: research/architecture_strategy.md §Human Escalation Flow

    Workflow:
        1. Read current daily_spend from Redis hash chimera:daily_spend:{agent_id}
        2. If daily_spend + proposed_amount > MAX_DAILY_LIMIT → raise BudgetExceededError
        3. If confidence_score < FINANCIAL_CONFIDENCE_THRESHOLD (0.95) → raise HumanInterventionRequired
        4. Execute the transaction
        5. Atomically update daily_spend in Redis via HINCRBYFLOAT
    """

    @functools.wraps(func)
    async def wrapper(*args: Any, **kwargs: Any) -> Any:
        # Extract the transaction proposal from arguments
        proposal: TransactionProposal | None = kwargs.get("proposal") or (
            args[1] if len(args) > 1 and isinstance(args[1], TransactionProposal) else None
        )
        redis_client = kwargs.get("redis_client") or (
            args[0].redis_client if hasattr(args[0], "redis_client") else None
        )

        if proposal is None:
            raise ValueError(
                "budget_check requires a TransactionProposal argument. "
                "Spec Ref: AI-016"
            )

        if redis_client is None:
            raise ValueError(
                "budget_check requires a redis_client. "
                "Spec Ref: specs/technical.md §5.5"
            )

        max_daily_limit = float(
            os.environ.get("MAX_DAILY_LIMIT_USDC", "50.0")
        )
        financial_confidence_threshold = float(
            os.environ.get("FINANCIAL_CONFIDENCE_THRESHOLD", "0.95")
        )

        # Step 1: Read current daily spend from Redis
        # Spec Ref: specs/technical.md §5.5 (Daily Spend Tracker)
        spend_key = f"chimera:daily_spend:{proposal.agent_id}"
        current_spend_raw = await redis_client.hget(spend_key, "total_usdc")
        current_spend = float(current_spend_raw) if current_spend_raw else 0.0

        # Step 2: Check budget limit
        if current_spend + proposal.amount_usdc > max_daily_limit:
            logger.warning(
                "Budget check FAILED for agent %s: $%.2f + $%.2f > $%.2f",
                proposal.agent_id,
                current_spend,
                proposal.amount_usdc,
                max_daily_limit,
            )
            raise BudgetExceededError(
                agent_id=proposal.agent_id,
                proposed_amount=proposal.amount_usdc,
                current_spend=current_spend,
                daily_limit=max_daily_limit,
            )

        # Step 3: Check financial confidence threshold (higher than standard 0.90)
        if proposal.confidence_score < financial_confidence_threshold:
            logger.info(
                "Financial HITL triggered for agent %s: confidence %.2f < %.2f",
                proposal.agent_id,
                proposal.confidence_score,
                financial_confidence_threshold,
            )
            raise HumanInterventionRequired(
                result_id=f"tx-{proposal.agent_id}-{uuid.uuid4().hex[:8]}",
                reason=(
                    f"Financial transaction confidence {proposal.confidence_score:.2f} "
                    f"below financial threshold {financial_confidence_threshold}"
                ),
                confidence_score=proposal.confidence_score,
                reasoning_trace=proposal.reasoning_trace,
            )

        # Step 4: Execute the wrapped function (the actual transaction)
        result = await func(*args, **kwargs)

        # Step 5: Atomically update daily spend in Redis
        # Spec Ref: specs/technical.md §5.5
        await redis_client.hincrbyfloat(
            spend_key, "total_usdc", proposal.amount_usdc
        )
        await redis_client.hincrby(spend_key, "tx_count", 1)
        await redis_client.hset(
            spend_key,
            "last_updated",
            datetime.now(timezone.utc).isoformat(),
        )

        logger.info(
            "Transaction approved for agent %s: $%.2f (new daily total: $%.2f)",
            proposal.agent_id,
            proposal.amount_usdc,
            current_spend + proposal.amount_usdc,
        )

        return result

    return wrapper


