class ConfidenceDecision(str, Enum):
    """
    Routing decisions based on confidence scoring.
    Spec Ref: NFR 1.0, NFR 1.1
    """

    AUTO_APPROVE = "auto_approve"  # > 0.90 (or > 0.95 for financial)
    ASYNC_APPROVAL = "async_approval"  # 0.70 - 0.90
    REJECT_RETRY = "reject_retry"  # < 0.70


class ReviewDecision(str, Enum):
    """HITL reviewer outcomes. Spec Ref: NFR 1.1"""

    APPROVED = "approved"
    EDITED = "edited"
    REJECTED = "rejected"


