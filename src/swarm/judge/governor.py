class ConfidenceScoredAction(BaseModel):
    """
    Every action generated by a Worker MUST include this metadata.
    The Judge uses these fields to route the result through the
    confidence-based HITL framework.

    Spec Ref: NFR 1.0, specs/technical.md §2.2
    """

    result_id: str = Field(
        default_factory=lambda: str(uuid.uuid4()),
        description="Unique identifier for this result.",
    )
    task_id: str = Field(
        ..., description="Reference to the originating Task."
    )
    agent_id: str = Field(
        ..., description="The Chimera Agent this result belongs to."
    )
    worker_id: str = Field(
        ..., description="Identifier of the Worker that produced this result."
    )
    confidence_score: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description=(
            "LLM-estimated confidence in the quality and safety of this result. "
            "Drives HITL routing per NFR 1.0."
        ),
    )
    reasoning_trace: str = Field(
        ...,
        min_length=10,
        description=(
            "Chain-of-thought explanation from the Worker. "
            "Required for audit trail and HITL review."
        ),
    )
    artifact_type: str = Field(
        ...,
        description="Type of the produced artifact: text, image_url, video_url, transaction, analysis.",
    )
    artifact_body: str = Field(
        ..., description="The generated content or URL reference."
    )
    sensitive_topics_detected: list[str] = Field(
        default_factory=list,
        description=(
            "Sensitive topic categories detected. "
            "Presence forces HITL routing regardless of confidence. "
            "Spec Ref: NFR 1.2"
        ),
    )
    state_version_at_start: int = Field(
        ...,
        ge=0,
        description="GlobalState version when Worker began. For OCC validation.",
    )
    execution_duration_ms: int = Field(
        default=0,
        ge=0,
        description="Wall-clock time the Worker spent on this task.",
    )
    tools_invoked: list[dict[str, Any]] = Field(
        default_factory=list,
        description="Audit log of MCP tool invocations during execution.",
    )

    @field_validator("confidence_score")
    @classmethod
    def validate_confidence_precision(cls, v: float) -> float:
        """Ensure confidence score has at most 4 decimal places."""
        return round(v, 4)


