class HumanInterventionRequired(Exception):
    """
    Raised when a Worker result fails the Judge's confidence threshold
    or triggers a sensitive topic filter, requiring HITL review.

    Spec Ref: NFR 1.1 (Automated Escalation Logic)
    """

    def __init__(
        self,
        result_id: str,
        reason: str,
        confidence_score: float,
        reasoning_trace: str,
    ):
        self.result_id = result_id
        self.reason = reason
        self.confidence_score = confidence_score
        self.reasoning_trace = reasoning_trace
        super().__init__(
            f"HITL Required for result {result_id}: {reason} "
            f"(confidence: {confidence_score:.2f})"
        )


class BudgetExceededError(Exception):
    """
    Raised when a proposed transaction would exceed the agent's daily
    spend limit. The transaction is NOT executed.

    Spec Ref: FR 5.2 (CFO Sub-Agent), AI-016
    """

    def __init__(
        self,
        agent_id: str,
        proposed_amount: float,
        current_spend: float,
        daily_limit: float,
    ):
        self.agent_id = agent_id
        self.proposed_amount = proposed_amount
        self.current_spend = current_spend
        self.daily_limit = daily_limit
        super().__init__(
            f"Budget exceeded for agent {agent_id}: "
            f"proposed ${proposed_amount:.2f} + current ${current_spend:.2f} "
            f"> limit ${daily_limit:.2f}"
        )


class OCCConflictError(Exception):
    """
    Raised when Optimistic Concurrency Control detects that the GlobalState
    has drifted since the Worker began its task.

    Spec Ref: FR 6.1, AI-019
    """

    def __init__(self, task_id: str, expected_version: int, actual_version: int):
        self.task_id = task_id
        self.expected_version = expected_version
        self.actual_version = actual_version
        super().__init__(
            f"OCC conflict for task {task_id}: "
            f"expected version {expected_version}, found {actual_version}"
        )


