from __future__ import annotations

import asyncio
import logging
import uuid
from datetime import datetime, timezone
from typing import Any

from pydantic import BaseModel, Field

logger = logging.getLogger("chimera.swarm.planner")


# =============================================================================
# Data Models — Spec Ref: specs/technical.md §2.1
# =============================================================================


class CampaignGoal(BaseModel):
    """
    High-level campaign goal from the Network Operator.
    Spec Ref: MA-001, SRS §3.1.1
    """
    campaign_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    goal_description: str = Field(
        ..., description="Natural language campaign objective."
    )
    agent_id: str = Field(..., description="Chimera Agent to execute this campaign.")
    priority: str = Field(default="medium", description="Campaign priority level.")
    budget_usdc: float = Field(default=0.0, ge=0, description="Total campaign budget.")
    target_platforms: list[str] = Field(default_factory=lambda: ["twitter"])
    constraints: list[str] = Field(
        default_factory=list,
        description="Behavioral constraints from SOUL.md directives.",
    )


class TaskDAGNode(BaseModel):
    """
    A node in the task Directed Acyclic Graph generated by the Planner.
    Spec Ref: SRS §3.1.1 (DAG generation)
    """
    task_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    task_type: str
    goal_description: str
    dependencies: list[str] = Field(
        default_factory=list,
        description="task_ids that must complete before this task can execute.",
    )
    priority: str = "medium"
    estimated_cost_usdc: float = 0.0


# =============================================================================
# Planner Service — Spec Ref: FR 6.0, MA-001
# =============================================================================


class PlannerService:
    """
    The Strategist: Decomposes campaign goals into task DAGs and
    manages the GlobalState for a Chimera Agent.

    Spec Ref:
        - SRS §3.1.1 (The Planner)
        - specs/functional.md MA-001 through MA-005
        - research/architecture_strategy.md §The Planner (Strategist)

    Responsibilities:
        1. Read campaign goals from Orchestrator
        2. Decompose into task DAG
        3. Push tasks to Redis task_queue
        4. React to context changes (dynamic re-planning)
        5. Monitor Worker pool utilization

    Implementation Status: SCAFFOLD
    """

    def __init__(
        self,
        redis_client: Any,
        mcp_client: Any | None = None,
        llm_model: str = "gemini-3-pro",
    ):
        """
        Initialize the Planner Service.

        Args:
            redis_client: Async Redis client for task queue operations.
            mcp_client: MCPClient for resource polling and context fetching.
            llm_model: LLM model for reasoning (default: Gemini 3 Pro).
                       Spec Ref: research/architecture_strategy.md §The Planner
        """
        self.redis_client = redis_client
        self.mcp_client = mcp_client
        self.llm_model = llm_model
        self._active_dags: dict[str, list[TaskDAGNode]] = {}

    async def decompose_goal(
        self, goal: CampaignGoal
    ) -> list[TaskDAGNode]:
        """
        Decompose a high-level campaign goal into a task DAG.

        Spec Ref: MA-001, SRS §3.1.1

        The Planner uses a reasoning-capable LLM (Gemini 3 Pro) to analyze
        the goal and generate a directed acyclic graph of sub-tasks.

        Args:
            goal: The campaign goal to decompose.

        Returns:
            List of TaskDAGNode forming the execution plan.
        """
        # SCAFFOLD: Will be implemented with pydantic-ai LLM call
        # The LLM analyzes the goal and returns structured task decomposition
        logger.info(
            "Decomposing goal for agent %s: %s",
            goal.agent_id,
            goal.goal_description[:100],
        )

        # Placeholder DAG — real implementation uses LLM-generated decomposition
        dag: list[TaskDAGNode] = []
        self._active_dags[goal.campaign_id] = dag
        return dag

    async def enqueue_tasks(
        self, agent_id: str, dag: list[TaskDAGNode]
    ) -> list[str]:
        """
        Push decomposed tasks to the agent's Redis task queue.

        Spec Ref: MA-001, specs/technical.md §5.2

        Uses Redis Streams for at-least-once delivery with consumer groups,
        ensuring resilience under Addis Ababa network conditions.

        Args:
            agent_id: The Chimera Agent's ID.
            dag: The task DAG to enqueue.

        Returns:
            List of Redis stream message IDs.
        """
        stream_key = f"chimera:task_queue:{agent_id}"
        message_ids: list[str] = []

        for node in dag:
            # Enqueue each task as a Redis Stream entry
            # Spec Ref: specs/technical.md §5.2, §5.3
            msg_id = await self.redis_client.xadd(
                stream_key,
                {
                    "task_id": node.task_id,
                    "task_type": node.task_type,
                    "goal_description": node.goal_description,
                    "priority": node.priority,
                    "dependencies": ",".join(node.dependencies),
                },
            )
            message_ids.append(msg_id)

        logger.info(
            "Enqueued %d tasks for agent %s",
            len(message_ids),
            agent_id,
        )
        return message_ids

    async def handle_context_change(
        self,
        campaign_id: str,
        change_event: dict[str, Any],
    ) -> list[TaskDAGNode]:
        """
        React to a context change by dynamically re-planning.

        Spec Ref: MA-002, SRS §3.1.1 (Dynamic Re-planning)

        If a news event shifts cultural context, or a Worker fails,
        the Planner prunes stale tasks and inserts replacements.

        Args:
            campaign_id: The campaign to re-plan.
            change_event: Description of the context change.

        Returns:
            Updated task DAG.
        """
        logger.info(
            "Context change detected for campaign %s: %s",
            campaign_id,
            change_event.get("type", "unknown"),
        )

        # SCAFFOLD: Will implement DAG pruning and re-insertion
        current_dag = self._active_dags.get(campaign_id, [])
        return current_dag

    async def check_balance_before_cost(
        self, agent_id: str, estimated_cost: float
    ) -> bool:
        """
        Verify sufficient wallet balance before creating cost-incurring tasks.

        Spec Ref: MA-006, FR 5.1

        The Planner MUST call get_balance before initiating any workflow
        that will spend funds.

        Args:
            agent_id: The agent whose balance to check.
            estimated_cost: Estimated cost of the planned tasks.

        Returns:
            True if balance is sufficient, False otherwise.
        """
        if self.mcp_client is None:
            logger.warning("No MCP client — cannot verify balance for agent %s", agent_id)
            return False

        # Route through MCP — Spec Ref: project-chimera.mdc Rule 2
        result = await self.mcp_client.call_tool(
            server_name="mcp-server-coinbase",
            tool_name="get_balance",
            arguments={"agent_id": agent_id, "tokens": ["USDC"]},
        )

        balance = result.data.get("USDC", 0.0)
        sufficient = balance >= estimated_cost

        if not sufficient:
            logger.warning(
                "Insufficient balance for agent %s: $%.2f < $%.2f needed",
                agent_id,
                balance,
                estimated_cost,
            )

        return sufficient
